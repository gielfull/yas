extension Data {
    /// Decodes a hex string, ignoring whitespace. Traps on invalid input (test fixtures only).
    init(hex: String) {
        let digits = hex.filter { !$0.isWhitespace }
        precondition(digits.count % 2 == 0, "odd hex length")
        var bytes: [UInt8] = []
        bytes.reserveCapacity(digits.count / 2)
        var index = digits.startIndex
        while index < digits.endIndex {
            let next = digits.index(index, offsetBy: 2)
            guard let byte = UInt8(digits[index..<next], radix: 16) else { preconditionFailure("bad hex") }
            bytes.append(byte)
            index = next
        }
        self.init(bytes)
    }
}
