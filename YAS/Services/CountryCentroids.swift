    static func centroid(for code: String) -> Centroid? {
        all[code.uppercased()]
    }

    /// Localized country name, falling back to the code itself.
    static func name(for code: String, locale: Locale = .current) -> String {
        locale.localizedString(forRegionCode: code.uppercased()) ?? code.uppercased()
    }

    /// Regional-indicator flag emoji for an ISO code ("US" -> the US flag).
    static func flag(for code: String) -> String {
        let scalars = code.uppercased().unicodeScalars.compactMap { scalar -> Unicode.Scalar? in
            guard scalar.value >= 65, scalar.value <= 90 else { return nil }
            return Unicode.Scalar(0x1F1E6 + scalar.value - 65)
        }
        guard scalars.count == 2 else { return "" }
        return String(String.UnicodeScalarView(scalars))
    }
